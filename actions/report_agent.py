"""
report_agent.py — VINCEVISION pentest report generator
───────────────────────────────────────────────────────
Compile recorded findings + authorized scope into a professional penetration
test report (Markdown). Pure documentation — performs no testing itself.

Reports are written to ``reports/`` (gitignored — confidential).

Actions: generate (write file) / preview (return text)
"""

import sys
import time
from datetime import datetime
from pathlib import Path


def _base_dir() -> Path:
    if getattr(sys, "frozen", False):
        return Path(sys.executable).parent
    return Path(__file__).resolve().parent.parent


REPORTS_DIR = _base_dir() / "reports"

SEV_ORDER = ("critical", "high", "medium", "low", "info")

METHODOLOGY = (
    "Testing was performed against the explicitly authorized scope listed below, "
    "following a standard methodology: reconnaissance, enumeration, vulnerability "
    "analysis, controlled validation, and reporting. All activities were confined to "
    "the authorized targets and rules of engagement."
)


def build_report(findings: list, scope: dict, meta: dict | None = None) -> str:
    meta = meta or {}
    now = datetime.now()
    title = meta.get("title", "Penetration Test Report")
    author = meta.get("author", "VINCEVISION")
    client = meta.get("client", "")

    counts = {s: 0 for s in SEV_ORDER}
    for f in findings:
        sev = str(f.get("severity", "info")).lower()
        counts[sev] = counts.get(sev, 0) + 1
    open_count = sum(1 for f in findings if f.get("status") == "open")

    lines = [
        f"# {title}",
        "",
        f"**Date:** {now.strftime('%Y-%m-%d')}  ",
        f"**Prepared by:** {author}  ",
    ]
    if client:
        lines.append(f"**Client:** {client}  ")
    if scope.get("authorized_by"):
        lines.append(f"**Authorization:** {scope['authorized_by']}  ")
    lines += ["", "---", "", "## Executive Summary", ""]
    lines.append(
        f"A total of **{len(findings)}** findings were recorded "
        f"(**{open_count}** still open): "
        f"{counts['critical']} critical, {counts['high']} high, "
        f"{counts['medium']} medium, {counts['low']} low, {counts['info']} informational."
    )
    lines += ["", "## Scope", ""]
    targets = scope.get("targets", [])
    if targets:
        for e in targets:
            t = e["target"] if isinstance(e, dict) else e
            note = e.get("note", "") if isinstance(e, dict) else ""
            lines.append(f"- `{t}`" + (f" — {note}" if note else ""))
    else:
        lines.append("_No scope recorded._")
    if scope.get("notes"):
        lines += ["", f"**Rules of engagement:** {scope['notes']}"]
    lines += ["", "## Methodology", "", METHODOLOGY, "", "## Findings", ""]

    if not findings:
        lines.append("_No findings recorded._")
    else:
        ordered = sorted(findings, key=lambda f: SEV_ORDER.index(
            str(f.get("severity", "info")).lower()
            if str(f.get("severity", "info")).lower() in SEV_ORDER else "info"))
        for f in ordered:
            sev = str(f.get("severity", "info")).upper()
            lines += [f"### #{f.get('id', '?')} — {f.get('title', '(untitled)')}", ""]
            lines.append(f"**Severity:** {sev}  ")
            if f.get("cvss") is not None:
                lines.append(f"**CVSS:** {f['cvss']}  ")
            if f.get("target"):
                lines.append(f"**Target:** `{f['target']}`  ")
            lines.append(f"**Status:** {f.get('status', 'open')}  ")
            lines += ["", f.get("description") or "_No description._", ""]
            lines += ["**Remediation:**", f.get("remediation") or "_No remediation provided._", ""]
            if f.get("evidence"):
                lines += ["**Evidence:**", "```", str(f["evidence"]), "```", ""]
            lines += ["---", ""]

    lines += ["## Remediation Summary", ""]
    open_findings = [f for f in findings if f.get("status") == "open"]
    if open_findings:
        for f in open_findings:
            lines.append(f"- **#{f.get('id')} ({f.get('severity')}):** "
                         f"{f.get('remediation') or 'Define remediation.'}")
    else:
        lines.append("All findings are resolved or accepted.")
    lines += ["", "---", "", "_Generated by VINCEVISION._", ""]
    return "\n".join(lines)


def _gather(scope_override=None):
    from actions.findings_agent import list_findings
    from actions.scope_agent import _load as load_scope
    findings = list_findings(limit=1000)
    scope = scope_override if scope_override is not None else load_scope()
    return findings, scope


def report_agent(parameters: dict, player=None, speak=None) -> str:
    params = parameters or {}
    action = str(params.get("action", "generate")).lower().strip()
    if action not in ("generate", "preview", "create", "export"):
        return "Say 'generate pentest report' or 'preview report', sir."

    try:
        findings, scope = _gather()
    except Exception as e:
        return f"Couldn't gather findings/scope: {e}"

    meta = {k: params[k] for k in ("title", "author", "client") if params.get(k)}
    text = build_report(findings, scope, meta)

    if action == "preview":
        return text

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    fname = params.get("filename") or f"pentest_report_{int(time.time())}.md"
    if not fname.endswith(".md"):
        fname += ".md"
    path = REPORTS_DIR / fname
    try:
        path.write_text(text, encoding="utf-8")
    except Exception as e:
        return f"Couldn't write the report: {e}"
    if speak:
        speak(f"Report generated with {len(findings)} findings, sir.")
    return f"✅ Report written to {path} ({len(findings)} findings)."
